/**
 * Интерфейс, описывающий структуру записи лога.
 * Определяет обязательные и опциональные поля для логирования.
 */
export interface LogEntry {
  /**
   * Уровень логирования (например: 'log', 'error', 'warn', 'debug', 'verbose').
   * Определяет серьёзность сообщения.
   */
  level: string;

  /**
   * Основное сообщение лога. Может быть любого типа — строка, объект, ошибка и т. д.
   */
  message: any;

  /**
   * Опциональный контекст логирования. Обычно содержит имя сервиса/модуля,
   * откуда был вызван логгер (например: 'AuthService', 'DatabaseModule').
   */
  context?: string;

  /**
   * Опциональная временная метка в формате ISO (например: '2024-01-01T12:00:00.000Z').
   * Указывает, когда было создано сообщение лога.
   */
  timestamp?: string;

  /**
   * Позволяет добавлять произвольные дополнительные поля в запись лога.
   * Например: user_id, request_id, duration и т. д.
   * Обеспечивает гибкость структуры логов без изменения интерфейса.
   */
  [key: string]: any;
}

/**
 * Тип, определяющий допустимые уровни логирования в системе.
 * Ограничивает возможные значения поля `level` в интерфейсе `LogEntry`.
 *
 * Доступные уровни:
 * - 'log' — стандартные информационные сообщения;
 * - 'error' — ошибки, требующие внимания;
 * - 'warn' — предупреждения о потенциальных проблемах;
 * - 'debug' — отладочные сообщения для разработки;
 * - 'verbose' — подробные детализированные сообщения (максимальный уровень детализации).
 */
export type LogLevel = 'log' | 'error' | 'warn' | 'debug' | 'verbose';
